export interface UtmParams {
  utm_source?: string;
  utm_medium?: string;
  utm_campaign?: string;
  utm_content?: string;
  utm_term?: string;
}

export function buildWhatsAppUrl(
  customMessage?: string,
  utm?: UtmParams
): string {
  const message = customMessage || LOCKED_COPY.whatsappMessages.hero;
  const baseUrl = LOCKED_COPY.business.whatsappBaseUrl;
  const params = new URLSearchParams();
  params.set("text", message);

  // Default UTM tags for dog daycare landing page
  params.set("utm_source", utm?.utm_source || "landing_page");
  params.set("utm_medium", utm?.utm_medium || "cta_button");
  params.set("utm_campaign", utm?.utm_campaign || "dog_daycare_dum_dum");
  if (utm?.utm_content) {
    params.set("utm_content", utm.utm_content);
  }

  return `${baseUrl}?${params.toString()}`;
}

export function buildPricingWhatsAppUrl(
  size: "Small" | "Medium" | "Large",
  utmContent?: string
): string {
  const message = `Hi Max Pet Corner! I would like to enquire about dog daycare pricing. My dog's size is ${size}. Please help me with the booking process.`;
  return buildWhatsAppUrl(message, {
    utm_source: "landing_page",
    utm_medium: "pricing_cta",
    utm_campaign: "dog_daycare_dum_dum",
    utm_content: utmContent || `pricing_${size.toLowerCase()}_dogs`,
  });
}

export function buildTrackedExternalUrl(
  baseUrl: string,
  utm: UtmParams
): string {
  try {
    const url = new URL(baseUrl);
    url.searchParams.set("utm_source", utm.utm_source || "landing_page");
    url.searchParams.set("utm_medium", utm.utm_medium || "cta_button");
    url.searchParams.set("utm_campaign", utm.utm_campaign || "dog_daycare_dum_dum");
    if (utm.utm_content) {
      url.searchParams.set("utm_content", utm.utm_content);
    }
    return url.toString();
  } catch {
    return baseUrl;
  }
}
